export function resolveUnitImageSlug(unitId: string): string {
  const slug = toUnitSlug(unitId);
  if (!slug) return "";

  if (UNIT_IMAGE_SLUG_MAP[slug]) {
    return UNIT_IMAGE_SLUG_MAP[slug];
  }

  // Strip duplicate sheet row suffix (e.g. "unit-name-2" -> "unit-name") if mapped
  const withoutDupSuffix = slug.replace(/-\d+$/, "");
  if (withoutDupSuffix !== slug && UNIT_IMAGE_SLUG_MAP[withoutDupSuffix]) {
    return UNIT_IMAGE_SLUG_MAP[withoutDupSuffix];
  }

  // Strip "-pure" suffix if present and resolve base unit slug
  if (slug.endsWith("-pure")) {
    const base = slug.slice(0, -5);
    return UNIT_IMAGE_SLUG_MAP[base] || base;
  }

  return slug;
}
